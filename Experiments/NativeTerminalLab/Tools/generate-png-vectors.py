#!/usr/bin/env python3
"""Independent PNG vectors using only struct/zlib, not ImageIO or the VT.

Print the deterministic NativePNGFixtures.swift file. Pixel samples are input
constants; expected output is not obtained from the decoder under test.
"""
import base64
import json
import struct
import zlib


def chunk(kind, data):
    return struct.pack('>I', len(data)) + kind + data + struct.pack('>I', zlib.crc32(kind + data))


def png(width, height, depth, color, rows, before=b'', interlace=0, compressed=None):
    header = struct.pack('>IIBBBBB', width, height, depth, color, 0, 0, interlace)
    pixels = zlib.compress(rows) if compressed is None else compressed
    return b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', header) + before + chunk(b'IDAT', pixels) + chunk(b'IEND', b'')


def filtered(rows):
    return b''.join(b'\0' + bytes(r) for r in rows)


def rgba(values):
    return [c for pixel in values for c in pixel]


vectors = []


def add(name, data, width, height, expected):
    vectors.append((name, data, width, height, expected))


add('rgb8', png(2, 2, 8, 2, filtered([[255, 0, 0, 0, 255, 0], [0, 0, 255, 255, 255, 255]])),
    2, 2, rgba([(255, 0, 0, 255), (0, 255, 0, 255), (0, 0, 255, 255), (255, 255, 255, 255)]))
colors = [(123, 45, 67, 1), (0, 255, 0, 0), (0, 0, 255, 128), (255, 0, 0, 255)]
add('rgba8', png(2, 2, 8, 6, filtered([rgba(colors[:2]), rgba(colors[2:])])), 2, 2, rgba(colors))
add('gray8', png(3, 1, 8, 0, filtered([[0, 128, 255]])), 3, 1,
    rgba([(0, 0, 0, 255), (128, 128, 128, 255), (255, 255, 255, 255)]))
add('grayAlpha8', png(2, 1, 8, 4, filtered([[200, 1, 70, 128]])), 2, 1,
    rgba([(200, 200, 200, 1), (70, 70, 70, 128)]))
add('gray1', png(4, 1, 1, 0, filtered([[0x50]])), 4, 1,
    rgba([(0, 0, 0, 255), (255, 255, 255, 255)] * 2))
palette = chunk(b'PLTE', bytes([255, 0, 0, 0, 255, 0, 0, 0, 255, 255, 255, 255]))
add('paletteAlpha2', png(2, 2, 2, 3, filtered([[0x10], [0xB0]]), palette + chunk(b'tRNS', bytes([255, 128, 0, 255]))),
    2, 2, rgba([(255, 0, 0, 255), (0, 255, 0, 128), (0, 0, 255, 0), (255, 255, 255, 255)]))
add('rgbTransparency', png(2, 1, 8, 2, filtered([[255, 255, 0, 255, 0, 0]]), chunk(b'tRNS', struct.pack('>HHH', 255, 255, 0))),
    2, 1, rgba([(255, 255, 0, 0), (255, 0, 0, 255)]))
add('gray16', png(3, 1, 16, 0, b'\0' + struct.pack('>HHH', 0, 32768, 65535)),
    3, 1, rgba([(0, 0, 0, 255), (128, 128, 128, 255), (255, 255, 255, 255)]))
add('rgba16', png(2, 1, 16, 6, b'\0' + struct.pack('>8H', 65535, 0, 0, 32768, 0, 65535, 0, 0)),
    2, 1, rgba([(255, 0, 0, 128), (0, 255, 0, 0)]))
# Adam7 passes of a 3x3 RGBA image. Filter None in each independent scanline.
colors = [(x * 100, y * 100, (x + y) * 50, 255) for y in range(3) for x in range(3)]
raw = b''
for x0, y0, dx, dy in [(0, 0, 8, 8), (4, 0, 8, 8), (0, 4, 4, 8), (2, 0, 4, 4), (0, 2, 2, 4), (1, 0, 2, 2), (0, 1, 1, 2)]:
    for y in range(y0, 3, dy):
        row = [colors[y * 3 + x] for x in range(x0, 3, dx)]
        if row:
            raw += b'\0' + bytes(rgba(row))
add('adam7', png(3, 3, 8, 6, raw, interlace=1), 3, 3, rgba(colors))

invalid = {
    'badDeflate': png(1, 1, 8, 6, b'', compressed=b'not zlib'),
    'tooWide': png(8193, 1, 8, 0, filtered([[0] * 8193])),
    'tooManyPixels': png(4096, 2048, 8, 0, filtered([[0] * 4096] * 2048)),
}
# A real two-frame APNG; the static decoder must not pretend to animate it.
ctl = lambda seq: struct.pack('>IIIIIHHBB', seq, 1, 1, 0, 0, 1, 10, 0, 0)
invalid['animated'] = (b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', 1, 1, 8, 6, 0, 0, 0))
    + chunk(b'acTL', struct.pack('>II', 2, 0)) + chunk(b'fcTL', ctl(0))
    + chunk(b'IDAT', zlib.compress(bytes([0, 255, 0, 0, 255])))
    + chunk(b'fcTL', ctl(1)) + chunk(b'fdAT', struct.pack('>I', 2) + zlib.compress(bytes([0, 0, 255, 0, 255])))
    + chunk(b'IEND', b''))

print('// Generated by Tools/generate-png-vectors.py (Python stdlib only).')
print('// Static test bytes and independent expected samples; do not edit by hand.')
print('import Foundation\n\nenum NativePNGFixtures {')
print('    struct Vector: Sendable {\n        let name: String, encoded: String\n        let width: Int, height: Int\n        let rgba: [UInt8]\n    }')
print('    static let vectors: [Vector] = [')
for name, data, width, height, expected in vectors:
    print(f'        .init(name: {json.dumps(name)}, encoded: "{base64.b64encode(data).decode()}", width: {width}, height: {height}, rgba: {expected}),')
print('    ]')
for name, data in invalid.items():
    print(f'    static let {name} = Data(base64Encoded: "{base64.b64encode(data).decode()}")!')
print('}')
